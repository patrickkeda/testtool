class I18n:
    """In-memory translation manager.

    Parameters
    ----------
    locale: str
        Initial locale code, e.g., "en_US" or "zh_CN".
    """

    def __init__(self, locale: str = "zh_CN") -> None:
        self._locale = locale if locale in _TRANSLATIONS else "zh_CN"

    @property
    def locale(self) -> str:
        return self._locale

    def set_locale(self, locale: str) -> None:
        if locale in _TRANSLATIONS:
            self._locale = locale

    def t(self, key: str) -> str:
        """Translate a key based on current locale, fallback to en_US or key.

        Parameters
        ----------
        key: str
            Translation key.

        Returns
        -------
        str
            Translated string.
        """
        table = _TRANSLATIONS.get(self._locale, {})
        if key in table:
            return table[key]
        # fallback to English
        return _TRANSLATIONS.get("en_US", {}).get(key, key)


